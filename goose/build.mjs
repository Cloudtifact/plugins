#!/usr/bin/env node
// Writes server.json, recipes/cloudy.yaml and deeplink.txt from the values below, and updates the address in README.md.
// The MCP address lives only here: change MCP_URL, then run `node goose/build.mjs`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const MCP_URL = "https://mcp.cloudtifact.com/mcp";
const VERSION = "0.3.3";
const NAME = "Cloudy";
const ID = "cloudy";
const DESCRIPTION = "Publish pages and docs to a stable link, then read, fix, reply to and resolve comments on them.";

const here = dirname(fileURLToPath(import.meta.url));
const out = (file, text) => writeFileSync(join(here, file), text);

if (DESCRIPTION.length > 100) throw new Error(`description is ${DESCRIPTION.length} chars; the MCP Registry allows 100`);

// Official MCP Registry entry (goose's extensions page will read the registry; see SUBMIT.md).
const server = {
  $schema: "https://static.modelcontextprotocol.io/schemas/2025-12-11/server.schema.json",
  name: "ai.usecloudy/cloudy",
  title: NAME,
  description: DESCRIPTION,
  version: VERSION,
  websiteUrl: "https://usecloudy.ai/docs/mcp",
  icons: [{ src: "https://usecloudy.ai/icon.png", mimeType: "image/png", sizes: ["512x512"] }],
  remotes: [{ type: "streamable-http", url: MCP_URL }],
};
out("server.json", `${JSON.stringify(server, null, 2)}\n`);

// goose Desktop install link (same query format as goose's own deeplink generator).
const q = (k, v) => `${k}=${encodeURIComponent(v)}`;
const deeplink = `goose://extension?${[
  "type=streamable_http",
  q("url", MCP_URL),
  q("id", ID),
  q("name", NAME),
  q("description", DESCRIPTION),
  "timeout=300",
].join("&")}`;
out("deeplink.txt", `${deeplink}\n`);

// Recipe: a goose session with Cloudy and the developer extension (to read the files it publishes).
const recipe = `# Generated by build.mjs. Edit there, not here.
version: "1.0.0"
title: Cloudy
description: Publish an HTML page or docs to a stable Cloudy link, then work through the comments people leave on it.
instructions: |
  You can publish to Cloudy with the cloudy extension. Cloudy gives pages and docs a stable link that people open and comment on. Spaces are private to the person's workspace unless they ask for a public link.

  - When the user wants a page, report, dashboard, prototype or any other HTML to look at or share, publish it with publish_page (html, plus files for the CSS, JS and images it references) and give them the links it returns. Say whether it's private or public, and which space it went into.
  - Before publishing something new, call find_spaces; if a space is already about the same topic, publish into it (add_to) instead of making another.
  - To update a page, publish again with space_id: same link, earlier versions kept.
  - Before changing a published page, read its open comments with list_comments. After addressing one, reply_to_comment with what you changed, then resolve_comment. If a comment needs a decision from the user, or you disagree, reply with your question or reason and leave it open.
  - Before building anything interactive (saved data, sign-ups, votes, uploads), call list_capabilities and use what it describes.
  - The first time, goose opens a browser window to sign in to Cloudy. Nothing else needs setting up.
activities:
  - "message: **Cloudy** publishes your pages to a stable link and brings people's comments back here."
  - Publish the HTML page I just made to Cloudy
  - Read the open comments on my Cloudy pages and address them
  - What have I published on Cloudy?
extensions:
  - type: streamable_http
    name: cloudy
    description: ${DESCRIPTION}
    uri: ${MCP_URL}
    timeout: 300
  - type: builtin
    name: developer
    timeout: 300
`;
out("recipes/cloudy.yaml", recipe);
// README.md: swap in the current address and install link.
const readme = readFileSync(join(here, "README.md"), "utf8")
  .replace(/goose:\/\/extension\?[^\s`]+/g, deeplink)
  .replace(/https:\/\/mcp\.[a-z0-9.-]+\/mcp/g, MCP_URL)
  .replace(/\(`mcp\.[a-z0-9.-]+`\)/g, `(\`${new URL(MCP_URL).host}\`)`);
out("README.md", readme);
console.log("wrote server.json, deeplink.txt, recipes/cloudy.yaml, README.md");
